"""Generates every committed contract artefact from the Python source of truth.

`render_all()` returns {relative path: text}; `sgw contracts` writes them, `sgw contracts-check` compares.
The TypeScript API types (`web/src/contracts/api.gen.ts`) come from `openapi-typescript` through pnpm and are
handled by the CLI, because they need Node.
"""

