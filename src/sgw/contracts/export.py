def render_all() -> dict[str, str]:
    from sgw.integrations import openapi as integrations_openapi

    events = golden.build_micro_events()
    streams = {"ops_ps17_hinge": golden.ops_stream(events), "run_ps17_water_continuity": golden.run_stream()}
    body = render_body(events)
    header = FixtureHeader.model_validate(
        {**golden.MICRO_HEADER, "body_sha256": hashlib.sha256(body.encode()).hexdigest()}
    )
    fixture = json.dumps(header.model_dump(mode="json"), separators=(",", ":"), sort_keys=True) + "\n" + body
    out: dict[str, str] = {
        "contracts/schema/events.json": _json(events_json_schema()),
        "contracts/schema/wire.json": _json(_schema(WireFrame, "SGW K4 SSE wire frame")),
        "contracts/schema/tools.json": _json(tool_schemas()),
        "contracts/schema/fixture_header.json": _json(_schema(FixtureHeader, "SGW K9 fixture header")),
        "contracts/schema/eventlog.json": _json(
            {
                "header": _schema(EventLogHeader, "SGW K19 event log header"),
                "line": _schema(EventLogLine, "SGW K19 event log line"),
            }
        ),
        "contracts/schema/eval_report.json": _json(_schema(EvalReport, "SGW K17 eval report")),
        "contracts/schema/llm_nodes.json": _json(_schema(LlmNodesFile, "SGW K14 LLM node config")),
        "contracts/schema/decision_case.json": _json(_schema(DecisionCase, "SGW K16 decision case")),
        "contracts/schema/users.json": _json(_schema(SeedUsers, "SGW K18 seeded identities")),
        "contracts/openapi.json": _json(openapi_document()),
        "contracts/openapi-v1.json": integrations_openapi.render(),
        "contracts/db/vocab_domains.sql": render_vocab_sql(),
        "contracts/vectors/action_hash.json": _json(golden.action_hash_vectors()),
        "contracts/vectors/webhook_signature.json": _json(golden.webhook_vectors()),
        "contracts/vectors/clock_ps17_hinge.json": _json(golden.hinge_vectors()),
        "contracts/golden/streams/ops_ps17_hinge.sse": streams["ops_ps17_hinge"],
        "contracts/golden/streams/run_ps17_water_continuity.sse": streams["run_ps17_water_continuity"],
        "data/fixtures/helene_micro/all.jsonl": fixture,
        "web/src/contracts/vocab.gen.ts": render_vocab_ts(),
        "web/src/contracts/wire.gen.ts": render_wire_ts(),
        "web/src/contracts/msw.gen.ts": render_msw(golden_examples(), streams),
        "web/src/contracts/vectors.gen.ts": TS_HEADER
        + "export const ACTION_HASH_VECTORS = "
        + json.dumps(golden.action_hash_vectors(), indent=2, ensure_ascii=False)
        + " as const;\n"
        + "export const SEVERITY_VECTORS = "
        + json.dumps(severity_vectors(), indent=2, ensure_ascii=False)
        + " as const;\n",
    }
    return out


def write_all(root: Path = REPO_ROOT) -> list[str]:
    written = []
    for rel, text in render_all().items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(rel)
    return written


def drift(root: Path = REPO_ROOT) -> list[str]:
    problems = []
    for rel, text in render_all().items():
        path = root / rel
        if not path.exists():
            problems.append(f"missing: {rel}")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"drift: {rel}")
    return problems
