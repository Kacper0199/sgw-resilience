def _reference_examples() -> dict[str, Any]:
    """Regions as `sgw seed` writes them (no geometry yet, so no bbox) and the two seeded staging yards at
    their synthetic network coordinates."""
    from sgw.approval.seed import REGIONS, YARDS

    regions = [
        Region(region_id=rid, state=state, county_fips=fips, name=name).model_dump(mode="json")  # type: ignore[arg-type]
        for rid, state, fips, name in REGIONS
    ]
    coords = {y["id"]: y for y in json.loads(NETWORK_PATH.read_text(encoding="utf-8"))["yards"]}
    assets = [
        Asset(
            asset_id=asset_id,
            domain=Domain.ELECTRIC,
            kind="staging_yard",
            region_id=region_id,
            lon_e6=round(coords[asset_id]["lon"] * 1_000_000),
            lat_e6=round(coords[asset_id]["lat"] * 1_000_000),
            criticality=0,
            critical_facility=False,
            customers_served=0,
            classification=Classification.C1,
            name=name,
        ).model_dump(mode="json")
        for asset_id, region_id, name in sorted(YARDS)
    ]
    listed = [{**a, "criticality": None} for a in assets]
    return {"listRegions": regions, "listAssets": listed, "getAsset": assets[0]}


