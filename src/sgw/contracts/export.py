REPO_ROOT = Path(__file__).resolve().parents[3]
TS_HEADER = "// Generated by `uv run sgw contracts`; do not edit. Source: src/sgw/contracts/.\n"
SQL_HEADER = "-- Generated by `uv run sgw contracts` from src/sgw/contracts/vocab.py; do not edit.\n"


def _json(obj: Any) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=False, sort_keys=False) + "\n"


def _schema(model: Any, title: str) -> dict[str, Any]:
    schema: dict[str, Any] = model.model_json_schema(mode="serialization")
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["title"] = title
    return schema


def _camel(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def render_vocab_ts() -> str:
    lines = [TS_HEADER.rstrip("\n")]
    for name, enum in ALL_VOCABS.items():
        const = name.upper()
        values = ", ".join(json.dumps(m.value) for m in enum)
        lines.append(f"export const {const} = [{values}] as const;")
        lines.append(f"export type {_camel(name)} = (typeof {const})[number];")
    lines.append("export const VOCABS = {")
    lines += [f"  {name}: {name.upper()}," for name in ALL_VOCABS]
    lines.append("} as const;")
    return "\n".join(lines) + "\n"


def render_vocab_sql() -> str:
    lines = [SQL_HEADER.rstrip("\n")]
    for name, enum in ALL_VOCABS.items():
        values = ", ".join("'" + m.value.replace("'", "''") + "'" for m in enum)
        lines.append(f"CREATE DOMAIN sgw_{name} AS text CHECK (VALUE IN ({values}));")
    return "\n".join(lines) + "\n"


def render_wire_ts() -> str:
    events = ", ".join(json.dumps(e.value) for e in WireEvent)
    return (
        TS_HEADER
        + 'import type { components } from "./api.gen";\n'
        + 'export type WireFrame = components["schemas"]["WireFrame"];\n'
        + f"export const WIRE_EVENTS = [{events}] as const;\n"
        + "export type WireEventName = (typeof WIRE_EVENTS)[number];\n"
        + "export const WIRE_VERSION = 1 as const;\n"
        + "export const HEARTBEAT_INTERVAL_S = 10 as const;\n"
        + "export const MISSED_HEARTBEATS_STALE = 3 as const;\n"
        + f"export const WEBHOOK_EVENT_TYPES = {json.dumps(list(WEBHOOK_EVENT_TYPES))} as const;\n"
        + "export function parseSseId(id: string): { stream: string; epoch: number; seq: number } {\n"
        + "  const m = /^(ops|run:[A-Za-z0-9_-]+)\\.(\\d+)\\.(\\d+)$/.exec(id);\n"
        + "  if (!m) throw new Error(`malformed SSE id: ${id}`);\n"
        + "  return { stream: m[1], epoch: Number(m[2]), seq: Number(m[3]) };\n"
        + "}\n"
    )


def _msw_path(path: str) -> str:
    return re.sub(r"\{([a-z_]+)\}", r":\1", path)


def render_msw(examples: dict[str, Any], streams: dict[str, str]) -> str:
    lines = [TS_HEADER.rstrip("\n"), 'import { http, HttpResponse } from "msw";', ""]
    lines.append(f"export const GOLDEN_STREAMS = {json.dumps(streams, indent=2)} as const;")
    lines.append(f"export const EXAMPLES = {json.dumps(examples, indent=2, ensure_ascii=False)} as const;")
    lines.append("")
    lines.append("const sse = (body: string) =>")
    lines.append(
        '  new HttpResponse(body, { headers: { "content-type": "text/event-stream", '
        '"cache-control": "no-cache" } });'
    )
    lines.append("")
    lines.append("export const handlers = [")
    for ep in ENDPOINTS:
        method = ep.method.lower()
        path = _msw_path(ep.path)
        if ep.sse and ep.response:
            lines.append(
                f'  http.{method}("{path}", () => HttpResponse.json({{ error: {{ code: "NOT_MOCKED", '
                f'message: "{ep.operation_id} has no golden stream" }} }}, {{ status: 501 }})),'
            )
        elif ep.sse:
            key = "ops_ps17_hinge" if ep.path.endswith("stream/ops") else "run_ps17_water_continuity"
            lines.append(f'  http.{method}("{path}", () => sse(GOLDEN_STREAMS.{key})),')
        elif ep.operation_id in examples:
            lines.append(
                f'  http.{method}("{path}", () => HttpResponse.json(EXAMPLES.{ep.operation_id}, '
                f"{{ status: {ep.status} }})),"
            )
        elif ep.status == 204:
            lines.append(f'  http.{method}("{path}", () => new HttpResponse(null, {{ status: 204 }})),')
        else:
            lines.append(
                f'  http.{method}("{path}", () => HttpResponse.json({{ error: {{ code: "NOT_MOCKED", '
                f'message: "{ep.operation_id} has no golden example" }} }}, {{ status: 501 }})),'
            )
    lines.append("];")
    return "\n".join(lines) + "\n"


