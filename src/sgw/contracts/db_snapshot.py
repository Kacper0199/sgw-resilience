"""K1 schema snapshot: a normalised, deterministic catalog listing of schema `public` after all migrations.
Built from `pg_catalog` (no pg_dump needed, same output on every OS); written to `contracts/db/schema.sql`."""

from __future__ import annotations

from pathlib import Path

import psycopg

SNAPSHOT_PATH = Path(__file__).resolve().parents[3] / "contracts" / "db" / "schema.sql"

_COLUMNS = """
SELECT c.relname, a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull,
       coalesce(pg_get_expr(d.adbin, d.adrelid), ''), a.attgenerated, a.attidentity
FROM pg_attribute a
JOIN pg_class c ON c.oid = a.attrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p', 'v') AND a.attnum > 0 AND NOT a.attisdropped
  AND c.relname NOT IN ('schema_migration', 'schema_migrations')
  AND NOT EXISTS (SELECT 1 FROM pg_depend dep
    WHERE dep.classid = 'pg_class'::regclass AND dep.objid = c.oid
      AND dep.deptype = 'e')
ORDER BY c.relname, a.attnum
"""
_CONSTRAINTS = """
SELECT c.relname, con.conname, pg_get_constraintdef(con.oid)
FROM pg_constraint con JOIN pg_class c ON c.oid = con.conrelid JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public' AND c.relname NOT IN ('schema_migration', 'schema_migrations')
  AND NOT EXISTS (SELECT 1 FROM pg_depend dep
    WHERE dep.classid = 'pg_class'::regclass AND dep.objid = c.oid
      AND dep.deptype = 'e')
ORDER BY c.relname, con.conname
"""
_INDEXES = """
SELECT tablename, indexname, indexdef FROM pg_indexes
WHERE schemaname = 'public' AND tablename NOT IN ('schema_migration', 'schema_migrations')
  AND NOT EXISTS (SELECT 1 FROM pg_depend dep
    WHERE dep.classid = 'pg_class'::regclass
      AND dep.objid = (quote_ident(schemaname) || '.' || quote_ident(tablename))::regclass
      AND dep.deptype = 'e')
ORDER BY tablename, indexname
"""
_TRIGGERS = """
SELECT c.relname, t.tgname, pg_get_triggerdef(t.oid)
FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public' AND NOT t.tgisinternal ORDER BY c.relname, t.tgname
"""
_DOMAINS = """
SELECT t.typname, pg_get_constraintdef(con.oid)
FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace JOIN pg_constraint con ON con.contypid = t.oid
WHERE n.nspname = 'public' AND t.typtype = 'd' ORDER BY t.typname, con.conname
"""
_HYPERTABLES = """
SELECT hypertable_name, column_name FROM timescaledb_information.dimensions
WHERE hypertable_schema = 'public' ORDER BY hypertable_name, column_name
"""
_GRANTS = """
SELECT g.table_name, g.grantee, string_agg(g.privilege_type, ',' ORDER BY g.privilege_type)
FROM information_schema.role_table_grants g
JOIN pg_namespace n ON n.nspname = g.table_schema
JOIN pg_class c ON c.relnamespace = n.oid AND c.relname = g.table_name
WHERE g.table_schema = 'public' AND g.grantee IN ('sgw_app', 'sgw_readonly')
  AND g.table_name NOT IN ('schema_migration', 'schema_migrations')
  AND NOT EXISTS (SELECT 1 FROM pg_depend dep
    WHERE dep.classid = 'pg_class'::regclass AND dep.objid = c.oid AND dep.deptype = 'e')
GROUP BY g.table_name, g.grantee ORDER BY g.table_name, g.grantee
"""


def snapshot(conninfo: str) -> str:
    lines = [
        "-- K1 normalised catalog snapshot of schema public; generated by `uv run sgw contracts --db`.",
        "-- Compare, never edit. Source: db/migrations/0001-0099.",
    ]
    with psycopg.connect(conninfo) as conn:
        lines.append("\n-- domains")
        lines += [f"DOMAIN {name} {definition}" for name, definition in conn.execute(_DOMAINS).fetchall()]
        current = None
        for table, col, typ, notnull, default, generated, identity in conn.execute(_COLUMNS).fetchall():
            if table != current:
                lines.append(f"\n-- {table}")
                current = table
            flags = " NOT NULL" if notnull else ""
            flags += f" DEFAULT {default}" if default and not generated else ""
            flags += f" GENERATED {default}" if generated else ""
            flags += " IDENTITY" if identity else ""
            lines.append(f"COLUMN {table}.{col} {typ}{flags}")
        lines.append("\n-- constraints")
        lines += [f"CONSTRAINT {t}.{n} {d}" for t, n, d in conn.execute(_CONSTRAINTS).fetchall()]
        lines.append("\n-- indexes")
        lines += [f"INDEX {d}" for _, _, d in conn.execute(_INDEXES).fetchall()]
        lines.append("\n-- triggers")
        lines += [f"TRIGGER {d}" for _, _, d in conn.execute(_TRIGGERS).fetchall()]
        lines.append("\n-- hypertables")
        lines += [f"HYPERTABLE {t}({c})" for t, c in conn.execute(_HYPERTABLES).fetchall()]
        lines.append("\n-- grants")
        lines += [f"GRANT {t} {g} {p}" for t, g, p in conn.execute(_GRANTS).fetchall()]
    return "\n".join(lines) + "\n"
