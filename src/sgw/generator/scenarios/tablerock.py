"""Table Rock fire-weather scenario (S-TRK, 2025-03-19..24 Eastern): the Red Flag protocol trigger on real
GSP observations, a synthetic Red Flag alert per trigger episode (K9 `weather.jsonl`), and the circuit
ranking table for the upstate feeders of the WP-06 world with the protocol decision attached (PS DC-32)."""

from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import numpy as np

from sgw.contracts.vocab import Tier
from sgw.generator.scenarios import common as cm
from sgw.generator.scenarios import fireweather as fwm
from sgw.generator.scenarios.weather import GSP_HOURLY
from sgw.generator.wind import epoch
from sgw.models.wildfire import ranking as rk

SCENARIO = "tablerock"
WINDOW = (datetime(2025, 3, 19, 4, tzinfo=UTC), datetime(2025, 3, 25, 4, tzinfo=UTC))
IGNITION_ANCHORS = (
    {"name": "Table Rock", "county_fips": "45077", "discovered_utc": "2025-03-22T13:26:00Z", "acres": 13845},
    {
        "name": "Table Rock Complex",
        "county_fips": "45045",
        "discovered_utc": "2025-03-24T15:05:00Z",
        "acres": 15973,
    },
)
ANCHOR_SOURCE = "NIFC WFIGS incidents; cause undetermined; shown for context, not modelled"
TOP_ACTION = 10
RANKING_HEADER = (
    "rank",
    "feeder_id",
    "fips",
    "customers",
    "veg_index",
    "overhead_km",
    "p_outage_window",
    "expected_faults_window",
    "p_ign_given_outage_peak",
    "expected_ignitions_window",
    "p_ignition_window",
    "ratio_to_average_window",
    "protocol",
)
PROTOCOL = (
    {
        "action": "red_flag_crew_restrictions",
        "tier": Tier.T2.value,
        "recommended": True,
        "applies_to": f"top {TOP_ACTION} circuits",
        "text": "Red Flag work rules on the listed circuits: no hot work, patrol before re-energising "
        "after a trip",
    },
    {
        "action": "recloser_one_shot_settings",
        "tier": Tier.T4.value,
        "recommended": True,
        "applies_to": f"top {TOP_ACTION} circuits",
        "text": "Refer to the qualified protection operator: one-shot reclosing on the listed circuits",
    },
    {
        "action": "targeted_de_energisation",
        "tier": Tier.T3.value,
        "recommended": False,
        "applies_to": "rank 1 only, last resort",
        "text": "Shown as the last-resort option; not recommended here: expected ignitions stay far "
        "below one per circuit and de-energisation removes power from customers for certain",
    },
)


FFWI_SENSITIVITY = (0.8, 2.0, 2.8)


def ffwi_ratio(ffwi_coef: float, window: list[rk.HourDriver], year: tuple[rk.HourDriver, ...]) -> float:
    with rk.ignition_weights(float(rk.value("ignition", "logit_kbdi_coef")), ffwi_coef):
        return rk.window_ratio(window, year, rk.calibrate(year, veg_mean()))


def circuits() -> list[rk.Circuit]:
    _, _, net = cm.world()
    counties = set(rk.value("network", "counties"))
    per_km = float(rk.value("network", "customers_per_overhead_km"))
    f = net.feeders
    return [
        rk.Circuit(fid, fips, int(cust), float(veg), float(cust) / per_km)
        for fid, fips, cust, veg in zip(f["id"], f["fips"], f["customers"], f["veg"], strict=True)
        if fips in counties
    ]


def veg_mean() -> float:
    _, _, net = cm.world()
    return float(np.mean(np.asarray(net.feeders["veg"], dtype=float)))


def build(out: Path) -> dict[str, Any]:
    fw = fwm.gsp()
    cal, year = fwm.calibration(veg_mean())
    window_obs = fw.between(*WINDOW)
    window = rk.drivers(window_obs, fw.kbdi_by_day)
    ranked = rk.rank(circuits(), window, cal, year)
    episodes = [e for e in fw.trigger.episodes if WINDOW[0] <= e.start_utc < WINDOW[1]]
    counties = sorted(rk.value("network", "counties"))
    s = cm.sink(SCENARIO, *WINDOW)
    for e in episodes:
        s.add(
            "WeatherAlert",
            epoch(e.start_utc),
            {
                "alert_id": f"RFW-SYN-UPSTATE-{e.start_utc:%m%d%H}",
                "product": "warning",
                "event_name": "Red Flag Warning",
                "severity": "severe",
                "area_fips": counties,
                "effective_utc": e.start_utc,
                "expires_utc": e.end_utc.replace(minute=59),
                "headline": "Red Flag protocol trigger (synthetic alert from GSP observations)",
            },
            key=f"rfw-{e.start_utc:%Y%m%d%H}",
            source="nws-alerts",
            region="SC",
        )
    header = cm.write_feed(
        out,
        SCENARIO,
        "weather",
        s.by_feed.get("weather", []),
        *WINDOW,
        calibration_source="GSP ASOS hourly 2023-01..2025-03; trigger per planner-handoff s3",
        note="Generated by `uv run python -m sgw.generator.scenarios generate tablerock`. "
        "Alerts are synthetic.",
    )
    cm.write_csv(
        out / "circuit_ranking.csv",
        RANKING_HEADER,
        [
            [
                c.rank,
                c.circuit.feeder_id,
                c.circuit.fips,
                c.circuit.customers,
                cm.r(c.circuit.veg, 3),
                cm.r(c.circuit.overhead_km, 1),
                f"{c.p_outage:.4f}",
                f"{c.expected_faults:.4f}",
                f"{c.peak_p_ign_given_outage:.4f}",
                f"{c.expected_ignitions:.6f}",
                f"{c.p_ignition:.6f}",
                f"{c.ratio_to_average_window:.1f}",
                "crew_restrictions_T2+recloser_one_shot_T4" if c.rank <= TOP_ACTION else "monitor",
            ]
            for c in ranked
        ],
    )
    total_ign = sum(c.expected_ignitions for c in ranked)
    summary = {
        "scenario": SCENARIO,
        "label": "synthetic ranking on real GSP weather",
        "window_utc": [cm.iso(WINDOW[0]), cm.iso(WINDOW[1])],
        "rule_id": fw.trigger.rule.rule_id,
        "fired_in_window": bool(episodes),
        "first_fire_utc": cm.iso(episodes[0].start_utc) if episodes else None,
        "episodes": [
            {
                "start_utc": cm.iso(e.start_utc),
                "end_utc": cm.iso(e.end_utc),
                "branches": list(e.branches),
                "active_hours": e.hours,
                "ffwi_max": cm.r(e.ffwi_max, 1),
                "rh_min_pct": cm.r(e.rh_min_pct, 1),
            }
            for e in episodes
        ],
        "kbdi_window": {
            d.day.isoformat(): cm.r(d.kbdi, 1)
            for d in fw.kbdi
            if WINDOW[0].date() <= d.day <= WINDOW[1].date()
        },
        "kbdi_branch_would_fire": any(
            h.kbdi_branch for h in fw.trigger.hours if WINDOW[0] <= h.t < WINDOW[1]
        ),
        "ignition_anchors": {"source": ANCHOR_SOURCE, "fires": list(IGNITION_ANCHORS)},
        "ranking": {
            "circuits": len(ranked),
            "counties": counties,
            "weather_station": "GSP",
            "expected_ignitions_all_circuits": cm.r(total_ign, 4),
            "ratio_to_average_window_all": cm.r(
                total_ign / sum(c.expected_ignitions / c.ratio_to_average_window for c in ranked), 1
            ),
            "top": [
                {
                    "rank": c.rank,
                    "feeder_id": c.circuit.feeder_id,
                    "p_ignition_window": cm.r(c.p_ignition, 6),
                    "ratio_to_average_window": cm.r(c.ratio_to_average_window, 1),
                }
                for c in ranked[:TOP_ACTION]
            ],
            "calibration": {
                "intercept": cm.r(cal.intercept, 6),
                "p0": cm.r(cal.p0, 6),
                "base_rate_per_100km_year": cm.r(cal.rate_per_km_year * 100.0, 4),
                "hours": cal.hours,
                "veg_mean": cm.r(cal.veg_mean, 4),
                "mean_annual_rain_in": cm.r(fw.mean_annual_rain_in, 2),
                "month_share_pct": {str(m): cm.r(v, 1) for m, v in rk.seasonal_shares(year, cal).items()},
                "observed_month_share_pct": {
                    str(m): v for m, v in rk.value("validation", "observed_month_share_pct").items()
                },
                "month_share_check": "in-sample: the weights were fitted to these same shares",
                "leave_one_month_out": rk.value("validation", "loo"),
            },
            "ffwi_weight_dependence": {
                "note": "the window score is driven by the FFWI logit weight (in-sample fit 2.0); "
                "mean-feeder ratio to an average window recomputed at other weights",
                "ratio_by_ffwi_coef": {
                    f"{fc:g}": cm.r(ffwi_ratio(fc, window, year), 1) for fc in FFWI_SENSITIVITY
                },
            },
            "drought_signal": "none: the fitted KBDI weight is 0, so on KBDI-only trigger days the "
            "ranking reflects wind and FFWI only and does not rank drought exposure",
        },
        "protocol": list(PROTOCOL),
        "weather_events": len(s.by_feed.get("weather", [])),
        "weather_body_sha256": header.body_sha256,
    }
    cm.write_json(out / "trigger.json", summary)
    cm.write_manifest(out, SCENARIO, ["weather.jsonl", "circuit_ranking.csv", "trigger.json"], [GSP_HOURLY])
    return summary
