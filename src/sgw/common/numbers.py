"""K10 numbers loader and generator.

    uv run python -m sgw.common.numbers --tex --py --ts --audit [--check]

`--tex` writes `docs/latex/shared/numbers.tex`, `--py` writes `src/sgw/common/numbers_gen.py`, `--ts` writes
`web/src/contracts/numbers.gen.ts` and `web/src/contracts/policies.gen.ts`. `--check` compares instead of
writing (drift). `--audit` reports registered values that appear as literals in `docs/` and `web/src`.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from functools import cache
from pathlib import Path

import yaml
from pydantic import Field, field_validator, model_validator

from sgw.contracts.base import Contract
from sgw.contracts.vocab import NumberKind, NumberLabel

REPO_ROOT = Path(__file__).resolve().parents[3]
NUMBERS_PATH = REPO_ROOT / "data" / "numbers" / "numbers.yaml"
TEX_OUT = Path("docs/latex/shared/numbers.tex")
PY_OUT = Path("src/sgw/common/numbers_gen.py")
TS_NUMBERS_OUT = Path("web/src/contracts/numbers.gen.ts")
TS_POLICIES_OUT = Path("web/src/contracts/policies.gen.ts")
ALLOWED_TARGETS = frozenset({"prd", "briefing", "deck", "video", "web", "code"})
POLICY_CHIP = "Assumed SGW policy"
_DIGIT_WORDS = ("Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine")


class NumberEntry(Contract):
    key: str = Field(pattern=r"^[a-z][a-z0-9_]*$")
    value: int | float
    unit: str
    label: NumberLabel
    kind: NumberKind
    source: str = Field(min_length=3)
    caveat: str
    allowed_in: list[str] = Field(min_length=1)
    handoff_s3: str | None
    tex_key: str | None = Field(default=None, pattern=r"^[a-z][a-z0-9_]*(\.[a-z0-9_]+)*$")

    @field_validator("allowed_in")
    @classmethod
    def _targets(cls, v: list[str]) -> list[str]:
        unknown = set(v) - ALLOWED_TARGETS
        if unknown:
            raise ValueError(f"unknown allowed_in targets {sorted(unknown)}")
        return v

    @model_validator(mode="after")
    def _kind_rules(self) -> NumberEntry:
        if self.kind is NumberKind.POLICY and self.label is not NumberLabel.A:
            raise ValueError(f"{self.key}: policy parameters are labelled A")
        if self.kind is NumberKind.POLICY and not self.key.startswith("policy_"):
            raise ValueError(f"{self.key}: policy keys start with policy_")
        if self.kind is not NumberKind.POLICY and self.handoff_s3 is None:
            raise ValueError(
                f"{self.key}: facts, computed values and assumptions must name their handoff-3 row"
            )
        return self

    @property
    def chip(self) -> str | None:
        return POLICY_CHIP if self.kind is NumberKind.POLICY else None


class NumbersFile(Contract):
    version: int
    numbers: dict[str, NumberEntry]


def load(path: Path = NUMBERS_PATH) -> NumbersFile:
    raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    entries = {k: {**v, "key": k} for k, v in raw["numbers"].items()}
    return NumbersFile.model_validate({"version": raw["version"], "numbers": entries})


@cache
def numbers() -> dict[str, NumberEntry]:
    return load().numbers


def value(key: str) -> int | float:
    return numbers()[key].value


def _macro(key: str) -> str:
    words = re.split(r"_", key)
    name = "".join(w.capitalize() for w in words)
    return "num" + "".join(_DIGIT_WORDS[int(c)] if c.isdigit() else c for c in name)


def _tex_value(v: int | float) -> str:
    if isinstance(v, int):
        text = f"{v:,}"
    else:
        text = format(v, ",.10f").rstrip("0")
        text = text + "0" if text.endswith(".") else text
    return text.replace(",", "{,}").replace("-", "\\textminus{}")


_TEX_SPECIAL = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def _tex_escape(text: str) -> str:
    return "".join(_TEX_SPECIAL.get(ch, ch) for ch in text)


def render_tex(nf: NumbersFile) -> str:
    lines = [
        "% Generated by `uv run python -m sgw.common.numbers --tex`; do not edit.",
        "% Source: data/numbers/numbers.yaml",
    ]
    for key in sorted(nf.numbers):
        e = nf.numbers[key]
        if not {"prd", "briefing", "deck"} & set(e.allowed_in):
            continue
        label = "P" if e.kind is NumberKind.POLICY else e.label.value
        fields = (e.tex_key or key, _tex_value(e.value), _tex_escape(e.unit), label, _tex_escape(e.source))
        lines.append("\\sgwdefnum" + "".join(f"{{{f}}}" for f in fields))
    return "\n".join(lines) + "\n"


def render_py(nf: NumbersFile) -> str:
    out = [
        '"""Generated by `uv run python -m sgw.common.numbers --py`; do not edit. '
        'Source: data/numbers/numbers.yaml."""',
        "",
        "from typing import Final",
        "",
    ]
    for key in sorted(nf.numbers):
        e = nf.numbers[key]
        if "code" not in e.allowed_in:
            continue
        typ = "int" if isinstance(e.value, int) else "float"
        out.append(f"{key.upper()}: Final[{typ}] = {e.value!r}")
    return "\n".join(out) + "\n"


def _ts_entry(e: NumberEntry) -> dict[str, object]:
    d: dict[str, object] = {
        "value": e.value,
        "unit": e.unit,
        "label": e.label.value,
        "kind": e.kind.value,
        "source": e.source,
        "caveat": e.caveat,
    }
    if e.chip:
        d["chip"] = e.chip
    return d


def render_ts(nf: NumbersFile, *, policies_only: bool) -> str:
    selected = {
        k: _ts_entry(e)
        for k, e in sorted(nf.numbers.items())
        if (e.kind is NumberKind.POLICY) == policies_only and ("web" in e.allowed_in or policies_only)
    }
    name = "POLICIES" if policies_only else "NUMBERS"
    body = json.dumps(selected, indent=2, ensure_ascii=False)
    return (
        "// Generated by `uv run python -m sgw.common.numbers --ts`; do not edit. "
        "Source: data/numbers/numbers.yaml.\n"
        f"export const {name} = {body} as const;\n"
        f"export type {'PolicyKey' if policies_only else 'NumberKey'} = keyof typeof {name};\n"
    )


def outputs(nf: NumbersFile, *, tex: bool, py: bool, ts: bool) -> dict[Path, str]:
    out: dict[Path, str] = {}
    if tex:
        out[TEX_OUT] = render_tex(nf)
    if py:
        out[PY_OUT] = render_py(nf)
    if ts:
        out[TS_NUMBERS_OUT] = render_ts(nf, policies_only=False)
        out[TS_POLICIES_OUT] = render_ts(nf, policies_only=True)
    return out


def _literal_forms(v: int | float) -> set[str]:
    forms = {str(v)}
    if isinstance(v, int):
        forms.add(f"{v:,}")

    def distinctive(form: str) -> bool:
        digits = form.replace(",", "").replace(".", "").lstrip("-")
        return len(digits) >= 4 and len(digits.rstrip("0")) >= 3

    return {f for f in forms if distinctive(f)}


AUDIT_GLOBS = ("docs/**/*.tex", "docs/**/*.md", "web/src/**/*.ts", "web/src/**/*.tsx")
AUDIT_SKIP = {TEX_OUT, TS_NUMBERS_OUT, TS_POLICIES_OUT, Path("docs/latex/shared/numbers-stub.tex")}
AUDIT_SKIP_DIRS = (Path("docs/latex/shared/diagrams"),)


def audit(nf: NumbersFile, root: Path = REPO_ROOT) -> list[str]:
    """Registered values of four or more digits typed as literals instead of macros or imports.

    In Markdown a literal is accepted when its registry key is named on the same line.
    """
    findings: list[str] = []
    forms = {f: k for k, e in nf.numbers.items() for f in _literal_forms(e.value)}
    if not forms:
        return findings
    pattern = re.compile(
        r"(?<![\w.,])(" + "|".join(re.escape(f) for f in sorted(forms, key=len, reverse=True)) + r")(?![\w])"
    )
    for glob in AUDIT_GLOBS:
        for path in sorted(root.glob(glob)):
            rel = path.relative_to(root)
            if (
                rel in AUDIT_SKIP
                or any(d in rel.parents for d in AUDIT_SKIP_DIRS)
                or "node_modules" in rel.parts
                or rel.name.endswith(".gen.ts")
            ):
                continue
            cites_keys = path.suffix == ".md"
            for lineno, line in enumerate(path.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
                for m in pattern.finditer(line):
                    if cites_keys and forms[m.group(1)] in line:
                        continue
                    findings.append(
                        f"{rel}:{lineno}: literal {m.group(1)} (use numbers key {forms[m.group(1)]})"
                    )
    return findings


def run(*, tex: bool, py: bool, ts: bool, do_audit: bool, check: bool, root: Path = REPO_ROOT) -> int:
    nf = load(root / "data" / "numbers" / "numbers.yaml")
    status = 0
    for rel, text in outputs(nf, tex=tex, py=py, ts=ts).items():
        path = root / rel
        if check:
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != text:
                print(f"drift: {rel} differs from a fresh export", file=sys.stderr)
                status = 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {rel}")
    if do_audit:
        findings = audit(nf, root)
        for f in findings:
            print(f, file=sys.stderr)
        if findings:
            status = 1
        else:
            print(f"audit: no literal registered values in {', '.join(AUDIT_GLOBS)}")
    return status


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m sgw.common.numbers", description=__doc__.splitlines()[0])
    parser.add_argument("--tex", action="store_true")
    parser.add_argument("--py", action="store_true")
    parser.add_argument("--ts", action="store_true")
    parser.add_argument("--audit", action="store_true")
    parser.add_argument(
        "--check", action="store_true", help="compare with committed files instead of writing"
    )
    args = parser.parse_args(argv)
    if not (args.tex or args.py or args.ts or args.audit):
        args.tex = args.py = args.ts = True
    return run(tex=args.tex, py=args.py, ts=args.ts, do_audit=args.audit, check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
