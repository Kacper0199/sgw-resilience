"""`sgw obs ...`: the optional `obs` compose profile, Prometheus + Grafana.

Only the obs services are started or stopped (`--no-deps`), so the shared core stack is never recreated.
Credentials are generated into var/secrets/ (git-ignored, 0600) and never printed.
"""

from __future__ import annotations

import json
import urllib.error
import urllib.request
from base64 import b64encode
from dataclasses import dataclass
from pathlib import Path
from typing import Annotated

import typer

from sgw.cli.support import (
    DB_NAME,
    PROJECT,
    CliError,
    compose_cmd,
    docker_bin,
    guard,
    load_credentials,
    new_password,
    read_env_file,
    run,
    secrets_dir,
    write_private,
)

app = typer.Typer(
    name="obs", help="Optional platform monitoring profile (Prometheus + Grafana).", no_args_is_help=True
)

PROFILE = "obs"
SERVICES = ("prometheus", "cadvisor", "postgres-exporter", "grafana")
MONITOR_ROLE = "sgw_monitor"
GRAFANA_ADMIN = "sgw-admin"
GRAFANA_URL = "http://127.0.0.1:3001"
PROMETHEUS_URL = "http://127.0.0.1:9091"
DASHBOARD_FOLDER = "sgw-platform"
DASHBOARD_UIDS = ("sgw-api", "sgw-containers", "sgw-postgres")
SYSTEM_METRICS_URL = f"{GRAFANA_URL}/dashboards/f/{DASHBOARD_FOLDER}/"
HEADER = "generated by `sgw obs init`; local only, never commit"


@dataclass(frozen=True)
class ObsSecrets:
    grafana_password: str
    monitor_password: str
    created: bool


def grafana_env_path() -> Path:
    return secrets_dir() / "grafana.env"


def exporter_env_path() -> Path:
    return secrets_dir() / "pg-exporter.env"


def monitor_dsn(password: str, host: str = "postgres", port: int = 5432) -> str:
    return f"postgresql://{MONITOR_ROLE}:{password}@{host}:{port}/{DB_NAME}?sslmode=disable"


def write_obs_secrets(rotate: bool = False) -> ObsSecrets:
    """Generate the Grafana admin password and the exporter DSN; existing values are kept unless rotate."""
    grafana_env, exporter_env = grafana_env_path(), exporter_env_path()
    grafana = {} if rotate or not grafana_env.is_file() else read_env_file(grafana_env)
    exporter = {} if rotate or not exporter_env.is_file() else read_env_file(exporter_env)
    grafana_password = grafana.get("GF_SECURITY_ADMIN_PASSWORD") or new_password()
    monitor_password = exporter.get("SGW_MONITOR_PASSWORD") or new_password()
    created = not grafana.get("GF_SECURITY_ADMIN_PASSWORD") or not exporter.get("SGW_MONITOR_PASSWORD")
    if created:
        write_private(
            grafana_env,
            {"GF_SECURITY_ADMIN_USER": GRAFANA_ADMIN, "GF_SECURITY_ADMIN_PASSWORD": grafana_password},
            HEADER,
        )
        write_private(
            exporter_env,
            {"SGW_MONITOR_PASSWORD": monitor_password, "DATA_SOURCE_NAME": monitor_dsn(monitor_password)},
            HEADER,
        )
    return ObsSecrets(grafana_password, monitor_password, created)


def monitor_role_statements(password: str) -> list[str]:
    """Idempotent SQL for a login that can only read statistics (pg_monitor), never application data."""
    from psycopg import sql

    role = sql.Identifier(MONITOR_ROLE)
    literal = sql.Literal(password)
    return [
        sql.SQL(
            "DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = {name}) THEN "
            "CREATE ROLE {role} LOGIN; END IF; END $$"
        )
        .format(name=sql.Literal(MONITOR_ROLE), role=role)
        .as_string(),
        sql.SQL(
            "ALTER ROLE {role} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE CONNECTION LIMIT 3 PASSWORD {pw}"
        )
        .format(role=role, pw=literal)
        .as_string(),
        sql.SQL("GRANT pg_monitor TO {role}").format(role=role).as_string(),
        sql.SQL("GRANT CONNECT ON DATABASE {db} TO {role}")
        .format(db=sql.Identifier(DB_NAME), role=role)
        .as_string(),
    ]


def ensure_monitor_role(password: str) -> None:
    import psycopg

    dsn = load_credentials().admin_dsn(DB_NAME)
    try:
        with psycopg.connect(dsn, autocommit=True, connect_timeout=5) as conn:
            for statement in monitor_role_statements(password):
                conn.execute(statement.encode())
    except psycopg.Error as error:
        raise CliError(
            f"could not create the {MONITOR_ROLE} role ({type(error).__name__}); is the stack up?"
        ) from None


def grafana_auth_header() -> str:
    values = read_env_file(grafana_env_path())
    token = f"{values['GF_SECURITY_ADMIN_USER']}:{values['GF_SECURITY_ADMIN_PASSWORD']}"
    return "Basic " + b64encode(token.encode()).decode()


def fetch_json(url: str, auth: str | None = None) -> object:
    request = urllib.request.Request(url, headers={"Authorization": auth} if auth else {})  # noqa: S310
    with urllib.request.urlopen(request, timeout=10) as response:  # noqa: S310
        return json.loads(response.read())


def provisioned_dashboards() -> dict[str, str]:
    """uid -> title of the dashboards Grafana serves in the SGW platform folder (admin login)."""
    found = fetch_json(
        f"{GRAFANA_URL}/api/search?type=dash-db&folderUIDs={DASHBOARD_FOLDER}", grafana_auth_header()
    )
    if not isinstance(found, list):
        raise CliError("unexpected Grafana search response")
    return {item["uid"]: item["title"] for item in found}


def scrape_targets() -> dict[str, str]:
    """job -> health of every Prometheus scrape target."""
    found = fetch_json(f"{PROMETHEUS_URL}/api/v1/targets")
    if not isinstance(found, dict):
        raise CliError("unexpected Prometheus targets response")
    return {t["labels"]["job"]: t["health"] for t in found["data"]["activeTargets"]}


@app.command("init")
@guard
def init(
    rotate: Annotated[bool, typer.Option("--rotate", help="Generate new obs passwords.")] = False,
) -> None:
    """Generate obs credentials into var/secrets/ and create the read-only `sgw_monitor` database role."""
    secrets = write_obs_secrets(rotate=rotate)
    ensure_monitor_role(secrets.monitor_password)
    state = "generated" if secrets.created else "kept (use --rotate to replace)"
    typer.echo(f"obs credentials {state}: {grafana_env_path()} and {exporter_env_path()}")
    typer.echo(f"database role {MONITOR_ROLE} ready (pg_monitor, connection limit 3)")
    if secrets.created and rotate:
        typer.secho(
            "Grafana keeps its first admin password in its volume: run `uv run sgw obs down --volumes` "
            "before `uv run sgw obs up`",
            fg="yellow",
        )


@app.command("up")
@guard
def up(timeout: Annotated[int, typer.Option(help="Seconds to wait for healthy services.")] = 180) -> None:
    """Start only the obs services (core must already be up) and wait until they are healthy."""
    secrets = write_obs_secrets()
    ensure_monitor_role(secrets.monitor_password)
    run(
        compose_cmd(
            "up", "-d", "--wait", "--wait-timeout", str(timeout), "--no-deps", *SERVICES, profile=PROFILE
        )
    )
    typer.echo("obs profile healthy:")
    typer.echo(f"  grafana      {GRAFANA_URL}  (user {GRAFANA_ADMIN}; password in {grafana_env_path()})")
    typer.echo(f"  prometheus   {PROMETHEUS_URL}")
    typer.echo(f"  Admin -> System metrics: {SYSTEM_METRICS_URL}")


@app.command("down")
@guard
def down(
    volumes: Annotated[
        bool, typer.Option("--volumes", help="Also delete Prometheus and Grafana data.")
    ] = False,
) -> None:
    """Stop and remove only the obs services; core keeps running."""
    run(compose_cmd("rm", "--stop", "--force", *SERVICES, profile=PROFILE))
    if volumes:
        for name in ("prometheus-data", "grafana-data"):
            run([docker_bin(), "volume", "rm", "--force", f"{PROJECT}_{name}"])


@app.command("check")
@guard
def check() -> None:
    """Prove the provisioned dashboards load (admin login) and list scrape target health."""
    try:
        dashboards = provisioned_dashboards()
        targets = scrape_targets()
    except (urllib.error.URLError, OSError) as error:
        raise CliError(
            f"obs profile not reachable ({type(error).__name__}); run `uv run sgw obs up`"
        ) from None
    for uid in DASHBOARD_UIDS:
        typer.echo(f"dashboard {uid:<16} {dashboards.get(uid, 'MISSING')}")
    for job, health in sorted(targets.items()):
        typer.echo(f"target    {job:<16} {health}")
    missing = [uid for uid in DASHBOARD_UIDS if uid not in dashboards]
    if missing:
        raise CliError(f"dashboards not provisioned: {', '.join(missing)}")
