def write_demo_passwords(password: str | None = None) -> int:
    """One generated password per K18 persona in var/demo.env (DEMO_PASSWORD_<USER_ID>), 0600. Existing
    values (also a legacy shared DEMO_PASSWORD) are kept; returns how many were added. With `password`
    (`sgw bootstrap --demo-password`) every persona gets that value instead, and
    DEMO_PASSWORD_MIN_LENGTH is lowered to its length when it is shorter than the default; returns how many
    personas were set. The value is never printed."""
    from sgw.api.users import DEFAULT_DEMO_PASSWORD_MIN_LENGTH, demo_password_min_length
    from sgw.contracts.identities import load_users, password_env_for

    path = demo_env_path()
    current = read_env_file(path) if path.is_file() else {}
    users = load_users(repo_root() / "data" / "seed" / "users.yaml")
    values = dict(current)
    if password is not None:
        check_demo_password(password)
        for user in users.users:
            values[password_env_for(user.user_id)] = password
        if len(password) < demo_password_min_length(values):
            values[MIN_LENGTH_ENV] = str(len(password))
        elif MIN_LENGTH_ENV in values and len(password) >= DEFAULT_DEMO_PASSWORD_MIN_LENGTH:
            values.pop(MIN_LENGTH_ENV)
        changed = values != current or not path.is_file()
        if changed:
            write_private(
                path, values, "generated by `sgw bootstrap`; demo persona passwords, local only, never commit"
            )
        return len(users.users)
    for user in users.users:
        values.setdefault(password_env_for(user.user_id), new_password())
    added = len(values) - len(current)
    if added or not path.is_file():
        write_private(
            path, values, "generated by `sgw bootstrap`; demo persona passwords, local only, never commit"
        )
    return added


MIN_LENGTH_ENV = "DEMO_PASSWORD_MIN_LENGTH"


def check_demo_password(password: str) -> None:
    from sgw.api.users import LOWEST_DEMO_PASSWORD_MIN_LENGTH

    if len(password) < LOWEST_DEMO_PASSWORD_MIN_LENGTH or password != password.strip():
        raise CliError(
            f"--demo-password needs at least {LOWEST_DEMO_PASSWORD_MIN_LENGTH} characters and no"
            " surrounding spaces"
        )


def ensure_opa_token(rotate: bool = False) -> tuple[str, bool]:
    """Shared bearer token for the stack's OPA, kept in var/secrets/opa.env (also the OPA container's env)."""
    path = secrets_dir() / "opa.env"
    current = "" if rotate or not path.is_file() else read_env_file(path).get("SGW_OPA_TOKEN", "")
    if current:
        return current, False
    token = new_password()
    write_private(path, {"SGW_OPA_TOKEN": token}, "generated by `sgw bootstrap`; OPA API token, never commit")
    return token, True


def write_credentials(rotate: bool = False) -> bool:
    """Generate missing passwords and the OPA token (all of them with rotate) and rewrite the derived env
    files from the stored values (idempotent: unchanged values give byte-identical files).

    Returns True when any secret was generated; existing ones are kept otherwise.
    gateway.env holds the llm_call writer DSN and the OPA token; the LLM key stays in SGW_ENV_FILE."""
    target = secrets_dir()
    postgres_env = target / "postgres.env"
    current = {} if rotate or not postgres_env.is_file() else read_env_file(postgres_env)
    values = {key: current.get(key) or new_password() for key in CREDENTIAL_KEYS}
    complete = bool(current) and all(current.get(key) for key in CREDENTIAL_KEYS)
    opa_token, opa_created = ensure_opa_token(rotate=rotate)
    superuser, owner, runtime, gateway = (values[key] for key in CREDENTIAL_KEYS)
    header = "generated by `sgw bootstrap`; local only, never commit"
    if not complete:
        write_private(postgres_env, values, header)
    write_private(
        target / "app.env",
        {
            "SGW_DB_USER": DB_RUNTIME,
            "SGW_DB_PASSWORD": runtime,
            "SGW_DB_NAME": DB_NAME,
            "SGW_DATABASE_URL": f"postgresql://{DB_RUNTIME}:{runtime}@postgres:5432/{DB_NAME}",
            "SGW_OPA_TOKEN": opa_token,
        },
        header,
    )
    write_private(
        target / "host.env",
        {
            "SGW_DATABASE_URL": f"postgresql://{DB_OWNER}:{owner}@127.0.0.1:{HOST_PORTS['postgres']}/{DB_NAME}",
            "SGW_RUNTIME_DATABASE_URL": (
                f"postgresql://{DB_RUNTIME}:{runtime}@127.0.0.1:{HOST_PORTS['postgres']}/{DB_NAME}"
            ),
            "SGW_GATEWAY_DATABASE_URL": (
                f"postgresql://{DB_GATEWAY}:{gateway}@127.0.0.1:{HOST_PORTS['postgres']}/{DB_NAME}"
            ),
            "SGW_ADMIN_DATABASE_URL": (
                f"postgresql://{DB_SUPERUSER}:{superuser}@127.0.0.1:{HOST_PORTS['postgres']}/postgres"
            ),
        },
        header,
    )
    write_private(
        target / "gateway.env",
        {
            "SGW_LLM_CALL_DSN": f"postgresql://{DB_GATEWAY}:{gateway}@postgres:5432/{DB_NAME}",
            "SGW_OPA_TOKEN": opa_token,
        },
        header,
    )
    return not complete or opa_created


GATEWAY_TOKENS_FILE = "gateway_tokens.env"
GATEWAY_TOKEN_TARGETS = {"api": "app.env", "worker": "app.env", "cli": "host.env"}


def ensure_gateway_tokens(rotate: bool = False) -> bool:
    """Per-service LLM gateway caller tokens (security audit M4). The tokens live in gateway_tokens.env; the
    api and worker read theirs from app.env, the host CLI from host.env, and the gateway gets only their
    SHA-256 digests in gateway.env. Returns True when tokens were generated."""
    from services.llm_gateway.callers import SERVICES, token_sha256

    target = secrets_dir()
    store = target / GATEWAY_TOKENS_FILE
    current = {} if rotate or not store.is_file() else read_env_file(store)
    keys = {service: f"SGW_GATEWAY_TOKEN_{service.upper()}" for service in SERVICES}
    tokens = {key: current.get(key) or new_password() for key in keys.values()}
    created = tokens != current
    header = "generated by `sgw bootstrap`; local only, never commit"
    if created:
        write_private(store, tokens, header)
    updates: dict[str, dict[str, str]] = {}
    for service, filename in GATEWAY_TOKEN_TARGETS.items():
        updates.setdefault(filename, {})[keys[service]] = tokens[keys[service]]
    updates["gateway.env"] = {
        "LLM_CALLER_TOKEN_SHA256": ",".join(
            f"{service}:{token_sha256(tokens[key])}" for service, key in keys.items()
        )
    }
    for filename, extra in updates.items():
        path = target / filename
        values = read_env_file(path) if path.is_file() else {}
        if any(values.get(k) != v for k, v in extra.items()):
            write_private(path, {**values, **extra}, header)
    return created


def prepare_llm_paths() -> None:
    placeholder = var_dir() / "llm.env"
    if not placeholder.exists():
        write_private(placeholder, {}, "placeholder: no LLM key, gateway runs in replay mode")
    spend = llm_spend_dir()
    spend.mkdir(parents=True, exist_ok=True)
    hand_to_containers(spend)


