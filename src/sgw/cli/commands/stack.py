def mode_env(demo: bool) -> dict[str, str]:
    """Interpolation values for compose: the stack defaults to DEMO_MODE=0 with Secure cookies. The demo
    gateway answers from recordings first and calls the model for a question nobody recorded
    (`replay_then_live`, D-100 Q-10; the gateway's daily cap holds) and serves a recorded answer after the
    time the live call took when recorded, capped; an `LLM_MODE` or `LLM_REPLAY_PACE_MAX_S` already
    set wins."""
    if not demo:
        return {"SGW_DEMO_MODE": "0"}
    return {
        "SGW_DEMO_MODE": "1",
        "SGW_COOKIE_SECURE": "0",
        "LLM_MODE": os.environ.get("LLM_MODE") or "replay_then_live",
        "LLM_REPLAY_PACE_MAX_S": os.environ.get("LLM_REPLAY_PACE_MAX_S") or DEMO_REPLAY_PACE_MAX_S,
    }


DEMO_REPLAY_PACE_MAX_S = "12"
POLICY_DIRS = ("policy", "infra/opa")


def policy_digest(root: Path | None = None) -> str:
    """SHA-256 over every file OPA mounts. OPA reads its files once at start, so compose puts this digest on
    the container as a label and `up` recreates OPA whenever a policy or its data changes."""
    base = root or repo_root()
    digest = hashlib.sha256()
    for directory in POLICY_DIRS:
        for path in sorted(p for p in (base / directory).rglob("*") if p.is_file()):
            digest.update(path.relative_to(base).as_posix().encode())
            digest.update(b"\0")
            digest.update(path.read_bytes())
            digest.update(b"\0")
    return digest.hexdigest()


def stack_env(demo: bool) -> dict[str, str]:
    return {
        **mode_env(demo),
        "SGW_POLICY_DIGEST": policy_digest(),
        demo_goto_role.DSN_KEY: demo_goto_role.compose_dsn(demo),
    }


@app.command()
@guard
def up(
    profile: ProfileOpt = "core",
    build: Annotated[bool, typer.Option("--build", help="Rebuild local images first.")] = False,
    timeout: Annotated[int, typer.Option(help="Seconds to wait for healthy services.")] = 240,
    demo: DemoOpt = False,
) -> None:
    """Start the stack and wait until every service is healthy."""
    preflight()
    goto_statements = demo_goto_role.statements_for(demo)
    with_obs = profile == "obs"
    if with_obs:
        from sgw.cli.commands.obs import ensure_monitor_role, write_obs_secrets

        obs_secrets = write_obs_secrets()
    prepare_database(profile, demo, timeout, build)
    args = ["up", "-d", "--wait", "--wait-timeout", str(timeout), "--remove-orphans"]
    if build:
        args.append("--build")
    run(compose_cmd(*args, profile=profile), env=stack_env(demo))
    demo_goto_role.apply(goto_statements)
    if with_obs:
        ensure_monitor_role(obs_secrets.monitor_password)
    typer.echo(f"stack healthy ({'DEMO_MODE=1, synthetic demo identities' if demo else 'DEMO_MODE=0'}):")
    for name, port in HOST_PORTS.items():
        if name == "mlflow" and profile != "mlflow-ui":
            typer.echo(f"  {name:<12} not published (opt in: uv run sgw up --profile mlflow-ui)")
            continue
        typer.echo(f"  {name:<12} 127.0.0.1:{port}")


def prepare_database(profile: str, demo: bool, timeout: int, build: bool) -> None:
    """Start Postgres first and apply pending migrations, so the api never starts on an empty schema."""
    from sgw.cli.commands.database import apply_migrations

    args = ["up", "-d", "--wait", "--wait-timeout", str(timeout)]
    if build:
        args.append("--build")
    run(compose_cmd(*args, "postgres", "pg-port", profile=profile), env=stack_env(demo))
    applied = apply_migrations()
    if applied:
        typer.echo(f"{DB_NAME}: {len(applied)} migration(s) applied before the services start")


@app.command()
@guard
def down(profile: ProfileOpt = "core") -> None:
    """Stop and remove the stack's containers; data volumes are kept."""
    run(compose_cmd("down", "--remove-orphans", profile=profile))


@app.command()
@guard
def reset(
    yes: Annotated[bool, typer.Option("--yes", "-y", help="Do not ask for confirmation.")] = False,
    profile: ProfileOpt = "core",
    demo: DemoOpt = False,
) -> None:
    """Delete the stack's volumes (all local SGW data), start it again and apply migrations. The audit anchors
    of the deleted databases are retired, so the new chains verify."""
    if not yes:
        typer.confirm(f"Delete every volume of compose project '{PROJECT}'?", abort=True)
    goto_statements = demo_goto_role.statements_for(demo)
    run(compose_cmd("down", "--volumes", "--remove-orphans", profile=profile))
    for retired in retire_anchors(None):
        typer.echo(f"audit anchors retired: {retired}")
    run(compose_cmd("up", "-d", "--wait", "--wait-timeout", "240", profile=profile), env=stack_env(demo))
    import psycopg

    from sgw.cli.commands.database import apply_migrations

    try:
        apply_migrations(database=DB_NAME)
    except psycopg.Error as error:
        raise CliError(f"stack is up but migration failed: {error}") from None
    demo_goto_role.apply(goto_statements)


def retire_anchors(database: str | None) -> list[Path]:
    """Retire the audit anchors of one database (or of every database) whose chain is gone."""
    from sgw.approval import audit

    store = audit.AnchorStore(audit_dirs()[2])
    names = store.namespaces() if database is None else [database]
    return [p for p in (store.retire(n) for n in names) if p is not None]


@app.command("reset-db")
@guard
def reset_db(
    yes: Annotated[bool, typer.Option("--yes", "-y", help="Do not ask for confirmation.")] = False,
    database: Annotated[str, typer.Option("--database", "-d", help="Database to recreate.")] = DB_NAME,
) -> None:
    """Drop and recreate one database of the running stack (default: the demo database), retire its audit
    anchors and apply migrations; every volume and every other database is kept. Seed it after
    (`uv run sgw seed --demo`); running services reconnect."""
    import psycopg
    from psycopg import sql

    from sgw.cli.commands.database import apply_migrations

    if not yes:
        typer.confirm(f"Drop database '{database}' and all its data?", abort=True)
    try:
        with psycopg.connect(load_credentials().admin_dsn(), autocommit=True) as admin:
            admin.execute(sql.SQL("DROP DATABASE IF EXISTS {} WITH (FORCE)").format(sql.Identifier(database)))
    except psycopg.Error as error:
        raise CliError(f"drop of {database} failed: {error}") from None
    typer.echo(f"dropped database {database}")
    for retired in retire_anchors(database):
        typer.echo(f"audit anchors retired: {retired}")
    try:
        apply_migrations(database=database, create=True)
    except psycopg.Error as error:
        raise CliError(f"{database} recreated but migration failed: {error}") from None
    typer.echo(f"next: uv run sgw seed{' --demo' if database == DB_NAME else f' -d {database}'}")


_UNITS = {
    "b": 1,
    "kb": 1000,
    "mb": 1000**2,
    "gb": 1000**3,
    "kib": 1024,
    "mib": 1024**2,
    "gib": 1024**3,
}


def parse_size(text: str) -> int:
    match = re.fullmatch(r"\s*([0-9.]+)\s*([A-Za-z]+)\s*", text)
    if not match:
        raise ValueError(f"unrecognised size: {text!r}")
    return int(float(match.group(1)) * _UNITS[match.group(2).lower()])


@dataclass(frozen=True)
class ContainerStat:
    service: str
    used: int
    limit: int
    cpu: str

    @property
    def used_mib(self) -> float:
        return self.used / 1024**2

    @property
    def limit_mib(self) -> float:
        return self.limit / 1024**2


def parse_stats_line(line: str, services: dict[str, str]) -> ContainerStat:
    row = json.loads(line)
    used_text, limit_text = row["MemUsage"].split("/")
    name = row["Name"]
    return ContainerStat(
        services.get(name, name), parse_size(used_text), parse_size(limit_text), row["CPUPerc"]
    )


def _docker_output(*args: str) -> str:
    try:
        result = subprocess.run(  # noqa: S603
            [docker_bin(), *args], capture_output=True, text=True, check=True
        )
    except subprocess.CalledProcessError as error:
        lines = (error.stderr or "").strip().splitlines()
        detail = lines[-1] if lines else f"exit {error.returncode}"
        raise CliError(f"docker {args[0]} failed: {detail}") from None
    return result.stdout


def collect_stats() -> list[ContainerStat]:
    listing = _docker_output(
        "ps",
        "--filter",
        f"label=com.docker.compose.project={PROJECT}",
        "--format",
        '{{.Names}}\t{{.Label "com.docker.compose.service"}}',
    )
    services = dict(line.split("\t", 1) for line in listing.splitlines() if "\t" in line)
    if not services:
        raise CliError(f"no running containers in compose project '{PROJECT}'; run `uv run sgw up`")
    output = _docker_output("stats", "--no-stream", "--format", "{{json .}}", *sorted(services))
    stats = [parse_stats_line(line, services) for line in output.splitlines() if line.strip()]
    return sorted(stats, key=lambda s: s.service)


def render_table(stats: list[ContainerStat]) -> list[str]:
    lines = [
        "| Service | Used (MiB) | Limit (MiB) | Used / limit | CPU |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for s in stats:
        share = 100 * s.used / s.limit if s.limit else 0.0
        lines.append(f"| {s.service} | {s.used_mib:.0f} | {s.limit_mib:.0f} | {share:.0f}% | {s.cpu} |")
    used = sum(s.used for s in stats) / 1024**2
    limit = sum(s.limit for s in stats) / 1024**2
    lines.append(f"| **total** | **{used:.0f}** | **{limit:.0f}** | {100 * used / limit:.0f}% | |")
    return lines


@app.command()
@guard
def stats(
    markdown: Annotated[
        Path | None, typer.Option(help="Append the snapshot as a Markdown section to this file.")
    ] = None,
    label: Annotated[
        str, typer.Option(help="Moment of the snapshot, e.g. idle or replay-900x.")
    ] = "snapshot",
) -> None:
    """Memory and CPU per SGW container (docker stats), plus host memory and swap."""
    snapshot = collect_stats()
    table = render_table(snapshot)
    host = hostinfo.memory_summary()
    for line in table:
        typer.echo(line)
    typer.echo(host)
    if markdown:
        stamp = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
        section = [f"### {label} ({stamp})", "", *table, "", f"Host: {host}", ""]
        with markdown.open("a", encoding="utf-8", newline="\n") as handle:
            handle.write("\n".join(section) + "\n")
        typer.echo(f"appended to {markdown}")


def secrets_present() -> bool:
    path = secrets_dir() / "postgres.env"
    return path.is_file() and "POSTGRES_PASSWORD" in read_env_file(path)
