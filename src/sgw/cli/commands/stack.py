def ensure_integration_key() -> str:
    """The integration master key (`var/secrets/integration.key`), shared by the api and webhooks services
    through compose.env and by host runs through the file itself."""
    from sgw.integrations.keys import KEY_FILE, ensure_key_file

    return ensure_key_file(secrets_dir() / KEY_FILE)


def write_compose_env(active_key: str, integration_key: str) -> Path:
    path = compose_env_path()
    uid, gid = run_ids()
    write_private(
        path,
        {
            "SGW_SECRETS_DIR": secrets_dir().as_posix(),
            "SGW_VAR_DIR": var_dir().as_posix(),
            "SGW_ENV_FILE": llm_env_file().as_posix(),
            "SGW_AUDIT_ACTIVE_KEY": active_key,
            "SGW_AUDIT_DATABASE_URL": runtime_dsn_for_containers(),
            "SGW_INTEGRATION_KEY": integration_key,
            "SGW_RUN_UID": str(uid),
            "SGW_RUN_GID": str(gid),
        },
        "generated by `sgw bootstrap`; local only (0600): holds the runtime DSN for audit-checkpoint"
        " and the integration master key",
    )
    return path


def preflight() -> None:
    """Fail before compose when bootstrap output is missing (compose itself keeps CI-safe defaults)."""
    missing = [name for name in REQUIRED_SECRET_FILES if not (secrets_dir() / name).is_file()]
    env_path = compose_env_path()
    values = read_env_file(env_path) if env_path.is_file() else {}
    missing += [key for key in REQUIRED_COMPOSE_KEYS if not values.get(key)]
    if missing:
        raise CliError(f"missing {', '.join(missing)}; run `uv run sgw bootstrap` (existing values are kept)")


@app.command()
@guard
def bootstrap(
    rotate: Annotated[
        bool,
        typer.Option("--rotate", help="Generate new passwords (the database volume must be reset after)."),
    ] = False,
    demo_password: Annotated[
        str | None,
        typer.Option(
            "--demo-password",
            help="Local demo only: give every demo person this password in var/demo.env (at least 3"
            " characters); seed the demo again after changing it.",
        ),
    ] = None,
) -> None:
    """Generate local stack credentials into var/ (git-ignored). Never reads or writes .env."""
    if demo_password is not None:
        check_demo_password(demo_password)
    created = write_credentials(rotate=rotate)
    tokens_created = ensure_gateway_tokens(rotate=rotate)
    demo_added = write_demo_passwords(demo_password)
    goto_created = demo_goto_role.ensure_secret(rotate=rotate)
    from sgw.cli.commands.obs import write_obs_secrets

    write_obs_secrets()
    prepare_llm_paths()
    audit = ensure_audit_key()
    compose_env = write_compose_env(audit.active_key, ensure_integration_key())
    secure_state_dirs()
    state = "generated" if created else "kept (use --rotate to replace)"
    typer.echo(f"credentials {state}: {secrets_dir()}")
    token_state = "generated" if tokens_created else "kept"
    typer.echo(f"LLM gateway caller tokens (api, worker, cli) {token_state}; the gateway holds digests only")
    typer.echo(f"compose settings: {compose_env}")
    if demo_password is None:
        typer.echo(
            f"demo persona passwords: {demo_env_path()} ({demo_added} added; open the file to read them)"
        )
    else:
        typer.echo(
            f"demo persona passwords: {demo_env_path()} (the --demo-password value for {demo_added} people;"
            " run `uv run sgw seed --demo` and `uv run sgw demo build` again if the demo was seeded before)"
        )
    goto_state = "generated" if goto_created else "kept"
    typer.echo(
        f"Load this moment role {goto_state}: {demo_goto_role.env_path()} (passed only by `sgw up --demo`)"
    )
    key_state = "generated" if audit.created else "kept"
    typer.echo(f"audit signing key {audit.active_key} {key_state}: {audit.key_dir}")
    env_file = llm_env_file()
    typer.echo(f"LLM key file for llm-gateway (not opened): {env_file}")
    if env_file == var_dir() / "llm.env":
        typer.echo("  placeholder without a key: replay mode only; for live calls put the key in")
        typer.echo("  llm.env at the repository root (copy llm.env.example) and rerun uv run sgw bootstrap")
    if created and rotate:
        typer.secho("passwords rotated: run `uv run sgw reset --yes` so the database uses them", fg="yellow")
    typer.echo("next: uv run sgw doctor && uv run sgw up")


