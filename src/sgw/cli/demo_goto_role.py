"""Demo-only database role behind "Load this moment" (`POST /api/demo/goto`, `sgw.api.demo_goto`).

`sgw bootstrap` keeps its password in var/secrets/demo_goto.env (0600, never in app.env); `sgw up --demo`
passes the DSN to the api and gives the role LOGIN, `sgw up` without `--demo` passes an empty DSN and sets
the role NOLOGIN. The password and DSNs are never printed."""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING

from sgw.cli.support import (
    DB_DEMO_GOTO,
    DB_OWNER,
    CliError,
    load_credentials,
    new_password,
    read_env_file,
    secrets_dir,
    write_private,
)

if TYPE_CHECKING:
    from psycopg import sql

PASSWORD_KEY = "SGW_DEMO_GOTO_PASSWORD"  # noqa: S105
DSN_KEY = "SGW_DEMO_GOTO_DSN"
HEADER = (
    "generated by `sgw bootstrap`; demo-only role for Load this moment, used by `sgw up --demo` only;"
    " local only, never commit"
)


def env_path() -> Path:
    return secrets_dir() / "demo_goto.env"


def container_dsn(password: str) -> str:
    return f"postgresql://{DB_DEMO_GOTO}:{password}@postgres:5432/postgres"


def ensure_secret(rotate: bool = False) -> bool:
    """Keep the stored password (a new one with rotate); returns True when a password was generated."""
    path = env_path()
    current = {} if rotate or not path.is_file() else read_env_file(path)
    password = current.get(PASSWORD_KEY) or new_password()
    values = {PASSWORD_KEY: password, DSN_KEY: container_dsn(password)}
    if values != current:
        write_private(path, values, HEADER)
    return password != current.get(PASSWORD_KEY)


def _stored() -> dict[str, str]:
    path = env_path()
    return read_env_file(path) if path.is_file() else {}


def compose_dsn(demo: bool) -> str:
    return _stored().get(DSN_KEY, "") if demo else ""


def stored_password() -> str:
    password = _stored().get(PASSWORD_KEY, "")
    if not password:
        raise CliError(
            f"no demo goto credentials at {env_path()}; run `uv run sgw bootstrap` (existing values are kept)"
        )
    return password


def _exists_guard(body: sql.Composable, negate: bool) -> sql.Composed:
    from psycopg import sql

    return sql.SQL(
        "DO $$ BEGIN IF {neg}EXISTS (SELECT 1 FROM pg_roles WHERE rolname = {name})"
        " THEN {body}; END IF; END $$"
    ).format(neg=sql.SQL("NOT " if negate else ""), name=sql.Literal(DB_DEMO_GOTO), body=body)


def enable_statements(password: str) -> list[sql.Composed]:
    """CREATEDB plus membership in the database owner (create the copy OWNER sgw, drop, rename, comment and
    grant on the sgw-owned database) and pg_signal_backend (DROP DATABASE ... WITH (FORCE) ends the other
    roles' sessions). No superuser, role creation, replication or RLS bypass."""
    from psycopg import sql

    role = sql.Identifier(DB_DEMO_GOTO)
    return [
        _exists_guard(sql.SQL("CREATE ROLE {role} NOLOGIN").format(role=role), negate=True),
        sql.SQL(
            "ALTER ROLE {role} LOGIN CREATEDB NOSUPERUSER NOCREATEROLE NOREPLICATION NOBYPASSRLS"
            " CONNECTION LIMIT 3 PASSWORD {pw}"
        ).format(role=role, pw=sql.Literal(password)),
        sql.SQL("GRANT {owner} TO {role} WITH INHERIT TRUE, SET TRUE").format(
            owner=sql.Identifier(DB_OWNER), role=role
        ),
        sql.SQL("GRANT {signal} TO {role}").format(signal=sql.Identifier("pg_signal_backend"), role=role),
    ]


def disable_statements() -> list[sql.Composed]:
    from psycopg import sql

    return [
        _exists_guard(
            sql.SQL("ALTER ROLE {role} NOLOGIN").format(role=sql.Identifier(DB_DEMO_GOTO)), negate=False
        )
    ]


def statements_for(demo: bool) -> list[sql.Composed]:
    """Without demo_goto.env no password was ever generated, so `up --demo` cannot have created the role."""
    if demo:
        return enable_statements(stored_password())
    return disable_statements() if env_path().is_file() else []


def apply(statements: list[sql.Composed]) -> None:
    if not statements:
        return
    import psycopg

    try:
        with psycopg.connect(load_credentials().admin_dsn(), autocommit=True, connect_timeout=5) as conn:
            for statement in statements:
                conn.execute(statement)
    except psycopg.Error as error:
        raise CliError(
            f"could not update the {DB_DEMO_GOTO} role ({type(error).__name__}); is the stack up?"
        ) from None
