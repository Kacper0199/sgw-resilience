"""Writes web/src/auth/personas.gen.ts from data/seed/users.yaml, the one source of the demo identities.

Run from the repository root: `uv run --frozen python web/scripts/build_personas.py`; with `--check` it exits
non-zero when the committed file is stale.
"""

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "data/seed/users.yaml"
TARGET = ROOT / "web/src/auth/personas.gen.ts"
COMMAND = "uv run --frozen python web/scripts/build_personas.py"
HEADER = f"// Generated by `{COMMAND}`; do not edit. Source: data/seed/users.yaml.\n"


def render() -> str:
    users = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))["users"]
    rows = "".join(
        f'  {{ user_id: "{u["user_id"]}", display_name: "{u["display_name"]}", '
        f'function: "{u["function"]}" }},\n'
        for u in users
    )
    return f"{HEADER}export const SEED_USERS = [\n{rows}] as const;\n"


def is_current() -> bool:
    return TARGET.exists() and TARGET.read_text(encoding="utf-8") == render()


def main() -> int:
    if "--check" in sys.argv:
        if is_current():
            return 0
        print(f"{TARGET.relative_to(ROOT)} is stale; run `{COMMAND}`")
        return 1
    TARGET.write_text(render(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
