"""One visual style for every SGW document figure.

The palette is read from the YAML front matter of DESIGN.md, so the product UI,
the Matplotlib charts and the LaTeX documents share one source of colour.

    uv run python docs/figures/style.py --tex      # rewrite docs/latex/shared/sgwpalette.tex
    uv run python docs/figures/style.py --check    # exit 1 if that file drifted from DESIGN.md
    uv run python docs/figures/style.py --fonts    # report which font family charts will use
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
from functools import cache
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
DESIGN_MD = REPO / "DESIGN.md"
PALETTE_TEX = REPO / "docs" / "latex" / "shared" / "sgwpalette.tex"

SANS_PREFERENCE = ("IBM Plex Sans", "Fira Sans", "Helvetica", "Arial", "DejaVu Sans")
MONO_PREFERENCE = ("IBM Plex Mono", "Fira Mono", "Menlo", "DejaVu Sans Mono")
TEX_FONT_FILES = (
    "FiraSans-Regular.otf",
    "FiraSans-Medium.otf",
    "FiraSans-SemiBold.otf",
    "FiraSans-Bold.otf",
    "FiraSans-Italic.otf",
    "FiraMono-Regular.otf",
)

FAN_ALPHAS = {50: 0.38, 80: 0.22, 95: 0.12}
MIN_TEXT_PT = 7


@cache
def design_tokens() -> dict:
    text = DESIGN_MD.read_text(encoding="utf-8")
    match = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not match:
        raise SystemExit(f"{DESIGN_MD}: no YAML front matter")
    return yaml.safe_load(match.group(1))


ROLE_TOKENS = {
    "hairline": "hair",
    "ink-muted": "muted",
    "secondary": "blue",
    "sev-critical": "crit",
    "neutral": "surface-2",
    "sev-advisory-fill": "blue-soft",
    "sev-critical-fill": "crit-soft",
    "sev-severe-fill": "warn-soft",
    "ok-fill": "#DDF0E3",
}


def colors() -> dict[str, str]:
    palette = {name: value.upper() for name, value in design_tokens()["colors"].items()}
    for role, token in ROLE_TOKENS.items():
        palette.setdefault(role, token if token.startswith("#") else palette[token])
    return palette


def tex_color_name(token: str) -> str:
    return "sgw" + "".join(part.capitalize() for part in token.split("-"))


def series() -> list[str]:
    c = colors()
    return [c["secondary"], c["ink-muted"], c["primary"], c["sev-critical"]]


def render_palette_tex() -> str:
    lines = [
        "% Generated by docs/figures/style.py from the front matter of DESIGN.md. Do not edit.",
        "% Rerun: uv run python docs/figures/style.py --tex",
    ]
    for token, value in colors().items():
        lines.append(f"\\definecolor{{{tex_color_name(token)}}}{{HTML}}{{{value.lstrip('#')}}}")
    return "\n".join(lines) + "\n"


def write_palette_tex() -> Path:
    PALETTE_TEX.write_text(render_palette_tex(), encoding="utf-8", newline="\n")
    return PALETTE_TEX


def palette_in_sync() -> bool:
    return PALETTE_TEX.exists() and PALETTE_TEX.read_text(encoding="utf-8") == render_palette_tex()


def _register_tex_fonts() -> None:
    from matplotlib import font_manager

    kpsewhich = shutil.which("kpsewhich")
    if not kpsewhich:
        return
    for name in TEX_FONT_FILES:
        found = subprocess.run(  # noqa: S603
            [kpsewhich, name], capture_output=True, text=True, check=False
        ).stdout.strip()
        if found:
            font_manager.fontManager.addfont(found)


@cache
def font_families() -> tuple[str, str]:
    from matplotlib import font_manager

    _register_tex_fonts()
    installed = set(font_manager.get_font_names())
    sans = next(f for f in SANS_PREFERENCE if f in installed or f == "DejaVu Sans")
    mono = next(f for f in MONO_PREFERENCE if f in installed or f == "DejaVu Sans Mono")
    return sans, mono


def apply() -> None:
    """Set Matplotlib rc parameters for every SGW chart."""
    import matplotlib as mpl
    from cycler import cycler

    c = colors()
    sans, mono = font_families()
    mpl.rcParams.update(
        {
            "font.family": "sans-serif",
            "font.sans-serif": [sans, "DejaVu Sans"],
            "font.monospace": [mono, "DejaVu Sans Mono"],
            "font.size": 8,
            "axes.titlesize": 9,
            "axes.titleweight": "semibold",
            "axes.labelsize": 8,
            "xtick.labelsize": MIN_TEXT_PT,
            "ytick.labelsize": MIN_TEXT_PT,
            "legend.fontsize": MIN_TEXT_PT,
            "text.color": c["ink"],
            "axes.labelcolor": c["ink"],
            "axes.edgecolor": c["hairline"],
            "axes.linewidth": 0.8,
            "axes.grid": True,
            "axes.grid.axis": "y",
            "grid.color": c["hairline"],
            "grid.linewidth": 0.6,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "axes.prop_cycle": cycler(color=series()),
            "xtick.color": c["ink-muted"],
            "ytick.color": c["ink-muted"],
            "figure.facecolor": c["surface"],
            "axes.facecolor": c["surface"],
            "savefig.facecolor": c["surface"],
            "legend.frameon": False,
            "lines.linewidth": 1.4,
            "pdf.fonttype": 42,
            "svg.fonttype": "none",
            "mathtext.fontset": "custom",
            "mathtext.rm": sans,
        }
    )


def label_footer(fig, label: str) -> None:
    """Every chart states whether its data are real, replayed or synthetic."""
    fig.text(
        0.995, -0.02, label, ha="right", va="top", fontsize=MIN_TEXT_PT - 0.5, color=colors()["ink-muted"]
    )


def save(fig, out_dir: Path, stem: str) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = [out_dir / f"{stem}.pdf", out_dir / f"{stem}.png"]
    fig.savefig(paths[0], bbox_inches="tight", metadata={"CreationDate": None})
    fig.savefig(paths[1], bbox_inches="tight", dpi=200)
    return paths


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tex", action="store_true", help="write the LaTeX palette file")
    parser.add_argument("--check", action="store_true", help="fail if the LaTeX palette drifted")
    parser.add_argument("--fonts", action="store_true", help="print the chart font families")
    args = parser.parse_args(argv)
    if args.tex:
        print(f"wrote {write_palette_tex().relative_to(REPO)}")
    if args.check and not palette_in_sync():
        print(f"{PALETTE_TEX.relative_to(REPO)} differs from DESIGN.md; run style.py --tex", file=sys.stderr)
        return 1
    if args.fonts:
        sans, mono = font_families()
        print(f"sans={sans} mono={mono}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
